def render(tables: dict[str, Any], comp: dict[str, Any], actual: dict[str, Any], cfg: dict[str, Any], root: Path = REPO) -> str:
    t, to, on = tables["tempo"], tables["timeouts"], tables["onside"]
    lines = [
        "# Coach decision report (M1 step 5)",
        "",
        "Generated by `uv run --project pipeline python -m pipeline.game`. Do not edit by hand.",
        "",
        "Three coach decisions the step 2 caller does not make, fitted from nflverse pbp (regular season, season-weighted with a 2-season half-life anchored at 2023, never 2024 or later). The bins, levels and minimum counts are designed (data/game/config.json); docs/MODEL.md labels each part.",
        "",
        "## 1. Tables",
        "",
        f"- Tempo (pre-snap run-off with the clock running): seasons {t['seasons'][0]}-{t['seasons'][-1]}, {t['snaps']:,} measured snaps, cells per level {[len(c) for c in t['cells']]}, minimum {t['minN']} snaps. Whole seconds 0 to {t['maxSeconds']}.",
        f"- Timeouts (per team per dead ball before a scrimmage snap): seasons {to['seasons'][0]}-{to['seasons'][-1]}, {to['deadBalls']:,} dead balls, cells per level {[len(c) for c in to['cells']]}, minimum {to['minN']}. Before a kickoff or a try (pooled rate per role, per 1,000,000 dead balls, observations): {to.get('beforeKickoffOrTry', {})}; by role and time bin (step 5c D, levels {[lv['dims'] for lv in to.get('special', {}).get('levels', [])]}): {to.get('special', {}).get('cells', [{}])[0]}.",
        f"- Onside (per kickoff): seasons {on['seasons'][0]}-{on['seasons'][-1]}, {on['kickoffs']:,} kickoffs, {on['attempts']:,} onside attempts, fitted cells per level {[len(c) for c in on['cells']]} (at least {on['minN']} kickoffs each, by score bin and time left); every other situation uses the designed rule (trailing by {on['designedRule']['trailingBy']}+ in the final {on['designedRule']['secondsLeftInGame']} s of the 4th quarter or overtime).",
        "",
        "Onside detection: a kickoff whose description says `onside`. " + _onside_line(actual.get("onsideCheck", {})),
        "",
        "Timeouts outside the fit: " + _timeout_line(actual.get("timeoutCounts", {})),
        "",
    ]
    lines += ["## 2. Component validation (C7)", "",
              f"Tolerances: data/game/tolerances.json, sha256 `{comp['tolerancesSha256']}`. Predicted = the fitted share functions applied to each real dead ball or kickoff; actual = what happened. Tempo is compared on snaps whose run-off could be measured (play timestamps, 2022 on).", ""]
    for key in ("inSample", "holdout"):
        if key not in comp:
            continue
        c = comp[key]
        fails = [m["id"] for m in c["metrics"] if m["status"] == "fail"]
        lines += [f"### {c['label']}", "", f"Gated failures: {', '.join(fails) if fails else 'none'}.", ""]
        if key == "holdout":
            lines += [POST_HOC, ""]
        lines += _table(c["metrics"]) + [""]
    if "holdout" not in comp:
        lines += ["The 2024-2025 run has not been made yet (in-sample only).", ""]
    lines += c3_section(root)
    return "\n".join(lines).rstrip() + "\n"


def c3_section(root: Path) -> list[str]:
    """Step 5b C3, in-sample: timeouts per team-game in the last 5:00 of Q4 by side x score3 (the
    calling team's view) x window, sim loop (data/game/calibration.insample.json) vs real 2016-2023
    (data/game/c3.real.json, `python -m pipeline.game.c3`), with the C7 per-dead-ball 2 pp check
    applied where the real dead-ball count is at least 100."""
    real_p, sim_p = root / "data/game/c3.real.json", root / "data/game/calibration.insample.json"
    if not real_p.exists() or not sim_p.exists():
        return []
    real = json.loads(real_p.read_text(encoding="utf-8"))["rows"]
    tol_p = root / "data/game/tolerances.json"
    accepted = set()
    if tol_p.exists():
        accepted = {d["metric"] for d in json.loads(tol_p.read_text(encoding="utf-8")).get("known_deviations", [])
                    if d.get("approved_by") == "Joseph" and d.get("scope", "holdout") == "insample"}
    diag = json.loads(sim_p.read_text(encoding="utf-8")).get("diagnostics", {})
    lines = ["## 3. Late timeouts by score (step 5b C3, in-sample)", "",
             "Timeouts per team-game in the dead ball before a Q4 scrimmage snap with 5:00 or less left (G5: 5:00 to 2:01, GF: final 2:00), by side and score3 "
             "from the calling team's view. Sim: the 10,000-game in-sample loop run. Real: 2016-2023, season-weighted. The check is the C7 threshold, 2 pp on the "
             "timeout rate per dead ball, where the real dead-ball count is at least 100; the per-team-game rows are shown, not gated.", "",
             "| Row (per dead ball) | Side | Score | Window | Sim per team-game | Real per team-game | Real timeouts | Sim per dead ball | Real per dead ball | Real dead balls | Check |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for side in ("offense", "defense"):
        for s3 in ("T", "0", "L"):
            for win in ("G5", "GF"):
                k = f"{side}.{s3}.{win}"
                sim = diag.get(f"diag.timeoutsPerTeamGame.{k}", {}).get("predicted")
                rate = diag.get(f"diag.timeoutRate.{k}", {})
                p, a, n = rate.get("predicted"), rate.get("actual"), rate.get("n", 0)
                check = "-" if p is None or a is None else "n below 100" if n < 100 else "pass" if abs(100 * (p - a)) <= 2 + 1e-9 else "fail"
                if check == "fail" and f"diag.timeoutRate.{k}" in accepted:
                    check = "accepted"
                r = real.get(k, {})
                lines.append(f"| `diag.timeoutRate.{k}` | {side} | {s3} | {win} | {'-' if sim is None else f'{sim:.3f}'} | {r.get('perTeamGame', 0):.3f} | {r.get('timeouts', 0):,} | "
                             f"{'-' if p is None else f'{100 * p:.2f}%'} | {'-' if a is None else f'{100 * a:.2f}%'} | {n:,} | {check} |")
    return lines + [""]


def _onside_line(c: dict[str, Any]) -> str:
    if not c:
        return ""
    return (f"2016-2023: {c['flagged']:,} of {c['kickoffs']:,} kickoffs are flagged; {c['flaggedWithin20Yards']:,} of them travelled 20 yards or less "
            f"({c['flaggedNoDistance']:,} have no distance), and {c['unflaggedUnder15Yards']:,} unflagged kickoffs went 15 yards or less (squibs and mis-hits).")


def _timeout_line(c: dict[str, Any]) -> str:
    if not c:
        return ""
    return (f"{c['challengeExcluded']:,} challenge or replay timeouts excluded; {c['beforeTry']:,} before a try and {c['beforeKickoff']:,} before a kickoff (not asked by the loop); "
            f"{c['afterTwoMinuteWarning']:,} after a two-minute warning (counted in the fit).")
