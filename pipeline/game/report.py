"""docs/COACH_REPORT.md: the fitted coach decision tables (tempo, timeouts, onside) and their
component validation (C7). Generated; deterministic for the same inputs."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from pipeline.caller.config import REPO


def _fmt(x: float | None, d: int = 2) -> str:
    return "" if x is None else f"{x:,.{d}f}"


def _table(rows: list[dict[str, Any]]) -> list[str]:
    out = ["| Metric | Predicted | Actual | n | 95% interval of actual | Tolerance | Status |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        tol = "" if r["tolerance"] is None else f"{r['tolerance']} {r['unit']}"
        out.append(f"| `{r['id']}` | {_fmt(r['predicted'])} | {_fmt(r['actual'])} | {r['n']:,.0f} | {_fmt(r['lo'])} to {_fmt(r['hi'])} | {tol} | {r['status']} |")
    return out


