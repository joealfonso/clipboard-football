"""docs/ENGINE_REPORT.md from the build's report dict. Deterministic: no timestamps."""

from __future__ import annotations

from typing import Any


def pct(x: float | None, d: int = 2) -> str:
    return "-" if x is None else f"{100 * x:.{d}f}"


def num(x: float | None, d: int = 2) -> str:
    return "-" if x is None else f"{x:.{d}f}"


def table(header: list[str], rows: list[list[str]]) -> list[str]:
    return ["| " + " | ".join(header) + " |", "|" + "---|" * len(header), *["| " + " | ".join(r) + " |" for r in rows], ""]


def metric_rows(summary: dict[str, Any]) -> list[list[str]]:
    out = []
    for m in summary["metrics"]:
        pp = m["unit"] == "pp"
        f = pct if pp else num
        ci = m["ci95"]
        out.append([
            f"`{m['id']}`",
            m["label"],
            f(m["predicted"]),
            f(m["actual"]),
            f"{m['plays']:,}",
            f"{m['n']:,.0f}",
            f"{m['nEff']:,.0f}",
            "-" if ci is None else f"{f(ci[0])} to {f(ci[1])}",
            f"{m['tolerance']} {m['unit']}",
            m["status"] + ("" if m["kind"] == "prediction" else f" ({m['kind']})"),
        ])
    return out


def render(r: dict[str, Any]) -> str:
    L: list[str] = [
        "# ENGINE_REPORT.md",
        "",
        "Generated by `uv run --project pipeline python -m pipeline.engine` from the repo root. Do not edit by hand; rerun the command. M1 step 4 (docs/specs/m1-step4-play-engine.md).",
        "",
        f"Config hash `{r['configHash']}`, matchup hash `{r['matchupHash']}`, tolerances hash `{r['tolerancesHash']}`, code hash `{r['codeHash']}`, nflreadpy {r['nflreadpy']}.",
        "",
        "## 1. Validation, 2024-2025 (never trained on)",
        "",
    ]
    v = r.get("validation")
    if v is None:
        L += ["Not run (`--skip-validation`).", ""]
    else:
        fails = v["gatedFailures"]
        L += [
            f"{'All gated metrics pass.' if not fails else f'{len(fails)} gated metric(s) fail: ' + ', '.join(f'`{x}`' for x in fails) + '.'} "
            f"Seed {v['seed']}, {v['simulationsPerPlay']} simulations per real play, generated league-average teams. Predicted and actual are percent for rates (unit pp), yards otherwise. Columns: plays is the count of real plays or snaps; n (weighted) is the sum of their weights (a split dropback counts by its depth share; in-sample also by season weight), and it is what the minN gate compares; effective n, (sum w)^2 / sum w^2, drives the interval. The interval is the 95% interval of the actual value (Wilson for rates, normal for yards). Kickoff rows check the hand tuning against 2025 and are not predictions. The `flags.*` rows count snaps with flags (the engine draws at most one one-team foul or one both-teams pair per snap); they were added after the tolerances were pre-registered and are not gated.",
            "",
        ]
        L += table(["metric", "what", "predicted", "actual", "plays", "n (weighted)", "effective n", "95% interval of actual", "tolerance", "status"], metric_rows(v))
    sens = r.get("sensitivity")
    if sens:
        teams = sens["teams"]
        L += [
            "### 1b. Sensitivity check: the team draw (report only, not gated)",
            "",
            f"The same 2024-2025 run with the 32 generated teams drawn from team seeds {', '.join(t for t in teams if t != 'flat')} instead of the validation seed, and with league-average teams (every rating 65, `flat`). Every other draw keeps seed {v['seed'] if v else ''}, so only the teams change. Rows: every gated failure and every gate within 0.5 of its tolerance. The pre-registered gate is the validation column; this table changes no status. Reproduce one column with `node --import ./scripts/engine/register.mjs scripts/engine/validate.ts <in> <out> <seed> <k> <teamSeed|flat>`; the whole table with `uv run --project pipeline python -m pipeline.engine`.",
            "",
        ]
        rows = []
        for mid, x in sens["rows"].items():
            f = pct if x["unit"] == "pp" else num
            rows.append([f"`{mid}`", x["status"], f(x["actual"]), f(x["pre"]), *[f(x["by"][t]) for t in teams], f"{x['tolerance']} {x['unit']}"])
        L += table(["metric", "status", "actual", "validation teams", *[f"teams {t}" for t in teams], "tolerance"], rows)
    sn = r.get("sneakSensitivity")
    if sn:
        L += [f"In-sample qbSneak 1-3 yard share, 2016-2023, season-weighted ({sn['plays']:,} sneaks), exact engine probability by team draw; actual {pct(sn['actual'])}%:", ""]
        L += table(["teams", "predicted %"], [[t, pct(p)] for t, p in sn["by"].items()])
    L += ["## 2. In-sample run, training seasons", ""]
    ins = r.get("inSample")
    if ins is None:
        L += ["Not run.", ""]
    else:
        L += [
            "The same metrics on the training seasons (pass leaves 2022-2023 only, where the leaf is known), each play and snap weighted by its season's fitting weight (half-life 2 seasons), as the tables were fitted, so n is a weighted count. These should match by construction up to the generated teams' sampling (32 teams), so they test the machinery, not the model. Statuses use the same tolerances for reference only.",
            "",
        ]
        L += table(["metric", "what", "predicted", "actual", "plays", "n (weighted)", "effective n", "95% interval of actual", "tolerance", "status"], metric_rows(ins))

    L += ["## 3. Play duration", ""]
    L += [
        "Source: nflverse pbp has no duration column. From 2022 on, `time_of_day` (the snap) and `end_clock_time` (the end of the play) are both UTC timestamps, and their difference is the play's length. The game clock runs during a live ball (Rule 4-3), so that is the clock the play used. Check against the game clock: on incompletions without a foul, followed by a snap in the same quarter, the clock stops at the end of the play and starts on the snap, so the change in `game_seconds_remaining` to the next snap should equal the measured duration.",
        "",
    ]
    L += table(
        ["season", "incompletions checked", "median error (s)", "within 1.5 s"],
        [[str(s), f"{int(c['n']):,}", num(c["medianError"]), pct(c["within1_5"], 1) + "%"] for s, c in sorted(r["durationChecks"].items())],
    )
    L += ["Measured subsample (B6): plays with both timestamps, 2022-2023, duration 0-30 s. Earlier seasons (pooled runs 2016-2021) draw seconds from the histogram of their class.", ""]
    rows = []
    for d in r["durationSubsample"]:
        classes = sorted(set(d["mixAll"]) | set(d["mixMeasured"]))
        mix = "; ".join(f"{c} {pct(d['mixMeasured'].get(c), 1)} vs {pct(d['mixAll'].get(c), 1)}" for c in classes)
        rows.append([d["group"], f"{d['measured']:,} of {d['all']:,}", num(d["meanSeconds"]), mix])
    L += table(["family", "measured of all (2022-2023)", "mean seconds", "class mix, measured vs all (%)"], rows)

    s = r["scrimmage"]
    L += ["## 4. Baseline cells and pools", ""]
    L += [f"Seasons {s['seasons'][0]}-{s['seasons'][-1]} (pass leaves {s['passSeasons'][0]}-{s['passSeasons'][-1]}), half-life {s['halfLifeSeasons']} seasons anchored at {s['weightAnchor']}. Stored cells per level (minimum 300 plays) and pools per level (minimum 100 plays, last level always kept):", ""]
    L += table(["level", "dimensions", "cells"], [[str(i), ", ".join(lv["dims"]) or "(global)", str(len(c))] for i, (lv, c) in enumerate(zip(s["levels"], s["cells"]))])
    L += table(["pool level", "dimensions", "pools"], [[str(i), ", ".join(lv["dims"]), str(len(c))] for i, (lv, c) in enumerate(zip(s["poolLevels"], s["pools"]))])
    L += ["Two-point tries: the source each leaf backs off to.", ""]
    L += table(["leaf", "source", "plays"], [[k, t["source"], f"{t['plays']:,.0f}"] for k, t in s["twoPoint"].items()])
    L += ["Per-leaf class shares in the training pools (season-weighted). Dropbacks without a known depth (sacks, scrambles, most throwaways) are split across the short, intermediate and deep leaves by the step 2 caller's depth shares in their situation, so those three leaves get the same sack and scramble rate in a given situation before matchups.", ""]
    lr = r["leafRates"]
    L += table(["leaf", "plays", "sack %", "scramble %", "int %", "inc %", "fumble %"],
               [[k, f"{v.get('plays', 0):,.0f}", pct(v.get("sack")), pct(v.get("scramble")), pct(v.get("int")), pct(v.get("inc")), pct(v.get("fumble", v.get("fumbleCatch")))] for k, v in lr.items()])

    fg = r["fieldGoals"]
    L += ["## 5. Field goals", ""]
    L += [f"Weighted logistic curve in distance and distance squared, 2016-2023, half-life 1 season. Capped beyond {fg['capAt']} yards (the longest distance with at least 20 attempts), falling linearly to 0 at {fg['maxDistance']}. Kick spot {fg['kickDepth']} yards behind the line (the most common measured depth). Training season make rate by band, actual vs the curve's mean prediction on that season's kicks (the drift: accuracy has risen).", ""]
    rows = []
    for row in r["fgBySeason"]:
        cells = [str(row["season"]), f"{row['attempts']:,}", pct(row["made"], 1)]
        for b in fg["bands"]:
            x = row[b["label"]]
            cells.append(f"{pct(x['actual'], 1)} / {pct(x['curve'], 1)} (n {x['n']})")
        rows.append(cells)
    L += table(["season", "unblocked", "made %", *[f"{b['label']} actual / curve" for b in fg["bands"]]], rows)
    L += ["Pre-registered expectation: 2024-2025 accuracy, especially 50+, is above the curve.", ""]

    L += ["## 6. Penalties", ""]
    pen = r["penalties"]
    L += [f"Rates per snap, 2016-2023, accepted and declined fouls both counted. Fouls by both teams on one run or pass snap: {pen['doublePer1000000'] / 10000:.3f}%.", ""]
    fam_rows = []
    for fam, levels in pen["families"].items():
        cell = levels[-1].get(fam) or levels[-1].get("clock")
        if cell is None:
            continue
        fam_rows.append([fam, *[f"{x / 10000:.3f}" for x in cell]])
    L += table(["family", *pen["ids"]], fam_rows)
    for key, title in (("gap", "2016-2023"), ("gapHoldout", "2024-2025")):
        g = r[key]
        L += [f"Unsupported fouls, {title}: {g['unsupportedYardsPerGame']:.1f} enforced yards per game not emitted, against {g['supportedYardsPerGame']:.1f} for supported fouls ({g['games']:,} games). This is the remaining penalty-yards gap step 5 will see.", ""]
        top = [x for x in g["rows"] if not x["supported"]][:12]
        L += table(["unsupported type", "fouls", "enforced", "yards per game", "per snap %"], [[x["type"], f"{x['fouls']:,}", f"{x['enforced']:,}", f"{x['yardsPerGame']:.2f}", pct(x["perSnap"], 3)] for x in top])

    L += ["## 7. Combine coverage", ""]
    c = r["combine"]
    L += [f"Drafted players, draft classes {c['draftClasses']['from']}-{c['draftClasses']['to']}. Players with each drill per position. A drill with fewer than 20 players for a position is not used there; a rating with no usable drill is designed for that position. Missing drills are not random (top prospects skip the 40 and the bench), and the percentile is over players with the drill. Name check: {c['combos']:,} first-last combinations, 0 match a real player in nflverse rosters 1999 on.", ""]
    L += table(["position", "players", "forty", "bench", "wt", "cone", "shuttle"],
               [[p, str(v["players"]), str(v["forty"]), str(v["bench"]), str(v["wt"]), str(v["cone"]), str(v["shuttle"])] for p, v in sorted(c["coverage"].items())])

    L += ["## 8. Matchup centering (D3)", ""]
    L += ["Per leaf, class probabilities over the training plays with the step 2 defense caller's preset shares: the baseline, with the raw designed multipliers, and with the centered multipliers. Largest gap to the baseline in percentage points.", ""]
    rows = []
    for leaf, ck in r["centering"].items():
        raw = max(abs(a - b) for a, b in zip(ck["baseline"], ck["raw"])) * 100
        cen = max(abs(a - b) for a, b in zip(ck["baseline"], ck["centered"])) * 100
        rows.append([leaf, str(ck["groups"]), f"{raw:.3f}", f"{cen:.6f}"])
    L += table(["leaf", "cell x formation groups", "raw gap (pp)", "centered gap (pp)"], rows)

    k = r["kickoffs2025"]
    if k:
        ci = k["ci95"]
        L += ["## 9. Kickoffs", "", f"Designed, tuned to 2025 (section 1 checks the tuning on {k['kickoffs']:,} non-onside 2025 kickoffs). Declared onside kicks in 2025: {k['recovered']} recovered of {k['onside']} ({pct(k['recovered'] / k['onside'] if k['onside'] else None, 1)}%, 95% interval {pct(ci[0], 1)} to {pct(ci[1], 1)}%). The designed recovery rate is that share.", ""]

    L += ["## 10. Size budget", ""]
    total = sum(r["sizes"].values())
    L += table(["file", "bytes"], [[f"`{p}`", f"{n:,}"] for p, n in r["sizes"].items()] + [["total", f"{total:,} of {r['budget']:,}"]])
    return "\n".join(L).rstrip() + "\n"
