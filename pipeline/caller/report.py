def _t(header: list[str], rows: list[list[str]]) -> list[str]:
    return ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"] + [
        "| " + " | ".join(r) + " |" for r in rows
    ]


def _pct(x: float | None, d: int = 1) -> str:
    return "-" if x is None else f"{100 * x:.{d}f}"


def _value_section(title: str, table: dict[str, Any], note: str = "") -> list[str]:
    seasons = table["seasons"]
    rows = [
        [f"`{r['value']}`" if r["value"] != "" else "(empty string)", str(r["target"])]
        + [str(r["counts"].get(s, 0)) for s in seasons]
        for r in table["rows"]
    ]
    out = [f"### {title}", ""]
    if note:
        out += [note, ""]
    return out + _t(["value", "maps to", *map(str, seasons)], rows) + [""]


def render(d: dict[str, Any]) -> str:
    L: list[str] = []
    L += [
        "# CALLER_REPORT.md",
        "",
        f"Generated by `{COMMAND}` from the repo root. Do not edit by hand; rerun the command.",
        "",
        f"- Config hash (catalog.json + config.json): `{d['configHash']}`",
        f"- Tolerances hash (tolerances.json): `{d['tolerancesHash']}`",
        f"- Code hash (pipeline/caller/*.py): `{d['codeHash']}`",
        f"- nflreadpy {d['nflreadpy']}. Seasons loaded: {d['seasonsLoaded']}. Regular season only. 2026 is in progress and out of range: not loaded.",
        "- Only counts and shares appear here. No player names or IDs.",
        "",
        "Contents: 1. Exclusions. 2. Mapping tables. 3. Coverage charting. 4. Blitz on runs vs dropbacks. "
        "5. QB sneak rule vs FTN flag. 6. Defense mapping mismatches. 7. Mix by season. 8. Fitted tables and backoff. "
        "9. Validation.",
        "",
    ]

    # 1
    L += ["## 1. Exclusions", "", "Every pbp row is counted once, by the first reason that applies, in this order.", ""]
    reasons = d["exclusionReasons"]
    rows = []
    for s in sorted(d["exclusions"]):
        e = d["exclusions"][s]
        rows.append([str(s)] + [str(e[r]) for r in reasons] + [str(d["inScope"][s]["scrimmage"]), str(d["inScope"][s]["try"])])
    L += _t(["season", *reasons, "scrimmage plays kept", "tries kept"], rows) + [""]

    # 2
    L += ["## 2. Mapping tables", "", "Every distinct value in the participation table, all rows, with counts per season and the designed target from data/caller/config.json. A value with no target fails the build.", ""]
    L += _value_section("offense_formation", d["values"]["formation"],
                        "Heavy also applies whatever the alignment when the personnel has 6+ OL or 3+ TE (see the offense personnel table).")
    L += _value_section("defense_coverage_type", d["values"]["coverage"],
                        "`None` as a target means the play is treated as coverage not charted: it is counted here, and left out of the coverage factor and the preset mapping.")
    L += _value_section("defense_man_zone_type", d["values"]["manZone"])
    L += _value_section("Personnel position tokens (offense and defense columns)", d["values"]["tokens"])
    L += _value_section("Defense personnel patterns", d["values"]["defensePatterns"],
                        "Pattern = position groups after the token table. Target = personnel group by DB count.")
    L += _value_section("Offense personnel patterns (OL and TE only)", d["values"]["offensePatterns"],
                        "OL0 means the old format, which lists OL only when it is not 5. Target = Heavy when 6+ OL or 3+ TE.")

    # 3
    cp = d["coveragePresence"]
    L += ["## 3. Coverage charting", "", "Share of scrimmage plays with `defense_coverage_type` charted, 2018-2025.", ""]
    for by, title in (("kind", "play type"), ("down", "down"), ("dist5", "distance"), ("zone6", "field zone"), ("score7", "score"), ("time5", "time")):
        seasons = sorted({s for _, s, _, _ in cp[by]})
        vals: dict[str, dict[int, float]] = {}
        for a, s, _, r in cp[by]:
            vals.setdefault(a, {})[s] = r
        rows = [[a] + [_pct(vals[a].get(s)) for s in seasons] for a in vals]
        L += [f"By {title}:", ""] + _t([title, *map(str, seasons)], rows) + [""]

    # 4
    b = d["blitz"]
    L += ["## 4. Blitz on runs vs dropbacks (FTN, 2022-2023)", "",
          "A diagnostic for the coverage assumption, not a gate. Blitz = FTN `n_blitzers` of 1 or more, charted on runs and dropbacks alike.", ""]
    L += _t(["play", "plays", "blitz %"], [[c, str(n), _pct(r)] for c, n, r in b["overall"]]) + [""]
    L += [f"Weighted mean of (dropback blitz rate minus run blitz rate) across {b['cells']} coarse cells with both: {100 * b['weightedDiff']:.1f} points.", ""]
    L += _t(["down", "distance", "play", "plays", "blitz %"], [[str(a), t, c, str(n), _pct(r)] for a, t, c, n, r in b["byDownDist"]]) + [""]

    # 5
    sn = d["sneak"]
    L += ["## 5. QB sneak rule vs FTN flag (2022-2023)", "",
          "Runs with an FTN row. The inferred rule is used only for 2016-2021; the flag is used from 2022.", ""]
    L += _t(["runs", "FTN flag", "inferred rule", "both", "flag only", "rule only"],
            [[str(sn["runs"]), str(sn["flag"]), str(sn["rule"]), str(sn["both"]), str(sn["flagOnly"]), str(sn["ruleOnly"])]]) + [""]
    if sn["flag"]:
        L += [f"Recall of the rule against the flag: {_pct(sn['both'] / sn['flag'])}%. Precision: {_pct(sn['both'] / sn['rule']) if sn['rule'] else '-'}%.", ""]

    # 6
    L += ["## 6. Defense mapping mismatches", "",
          "Mapped snaps (run and pass plays with personnel, box and coverage charted) whose real component differs from the preset's designed definition. The mapping is designed, not data-derived.", ""]
    mm = d["mismatch"]
    comps = list(next(iter(mm.values()))["shares"])
    L += _t(["period", "mapped snaps", *comps, "any"],
            [[p, str(v["n"])] + [_pct(v["shares"][c]) for c in comps] + [_pct(v["any"])] for p, v in mm.items()]) + [""]
    for p, v in mm.items():
        L += [f"Most common mismatched real calls, {p}:", ""]
        L += _t(["DBs", "box", "shell", "man/zone", "rush", "mapped to", "snaps", "% of mapped"],
                [[*k, str(n), _pct(sh)] for k, n, sh in v["top"]]) + [""]

    # 7
    L += ["## 7. Mix by season", ""]
    for name, mix in d["mixes"].items():
        seasons = mix["seasons"]
        rows = [[k] + [_pct(mix["rows"][k].get(s)) for s in seasons] for k in sorted(mix["rows"])]
        rows.append(["plays"] + [str(mix["totals"][s]) for s in seasons])
        L += [f"{name}:", ""] + _t(["", *map(str, seasons)], rows) + [""]

    # 8
    L += ["## 8. Fitted tables and backoff", "",
          f"Season weight = 0.5 ^ (({d['anchor']} - season) / {d['halfLife']}). A cell is stored when it has at least the factor's minimum unweighted plays. "
          "Backoff columns: share of 2024-2025 validation lookups that landed on each level (level 0 is the finest).", ""]
    rows = []
    for fid, info in d["fit"].items():
        bo = d["backoff"].get(fid, {})
        tot = sum(bo.values())
        levels = len(info["cells"])
        rows.append([
            fid, f"{info['seasons'][0]}-{info['seasons'][-1]}" if info["seasons"] else "-",
            str(info["plays"]), str(info["minPlays"]),
            " / ".join(str(c) for c in info["cells"]),
            " / ".join(_pct(bo.get(i, 0) / tot) if tot else "-" for i in range(levels)),
        ])
    L += _t(["factor", "seasons", "plays", "min per cell", "cells per level", "validation lookups per level %"], rows) + [""]
    L += ["Season weights: " + "; ".join(f"{s}: {w:.4f}" for s, w in d["weights"].items()) + ".", ""]
    L += ["Depth: fitted on 2022-2023 plain dropbacks only (no correction factors), per the lead's decision on 2026-11-11.", ""]
    L += [f"Generated table size: {d['tableBytes']} bytes in total ({', '.join(f'{k} {v}' for k, v in d['tableSizes'].items())}). Budget 300 KB.", ""]
    L += [f"Golden file: {d['golden']['n']} situations. Level coverage: " + ", ".join(f"{k} {v}" for k, v in d["golden"]["coverage"].items()) + ".", ""]

    # 8b
    tc = d.get("trainingCheck")
    if tc:
        L += ["## 8b. Training-data check (in-sample, no holdout)", "",
              "The caller's predicted rates against the seasons it was fitted on, for 4th-down calls, kneels and pass rate by down. "
              "In-sample, so agreement here is necessary, not sufficient. 4th-down go rates are fitted on 2021-2023 and punt vs field goal on 2016-2023, so both windows are shown.", ""]
        groups = ("passRateByDown", "fourthDown", "kneel")
        ids = [m.id for m in next(iter(tc.values())).metrics if m.group in groups]
        by = {lbl: {m.id: m for m in v.metrics} for lbl, v in tc.items()}
        rows = []
        for mid in ids:
            row = [next(m.label for m in by[next(iter(by))].values() if m.id == mid)]
            for lbl in by:
                m = by[lbl].get(mid)
                row += ["-", "-", "-"] if m is None else [str(m.n), _pct(m.predicted), _pct(m.actual)]
            rows.append(row)
        head = ["metric"] + [f"{lbl} {c}" for lbl in by for c in ("n", "predicted %", "actual %")]
        L += _t(head, rows) + [""]

    lc = d.get("lateCounts")
    if lc:
        L += ["## 8c. Late-window cells (step 5a, A5)", "",
              "Unweighted plays per late-window cell at the finest late level each changed factor gains (last 5:00 of the game, late score bins), "
              "2016-2023 and 2021-2023. A cell is stored with at least 150 plays.", ""]
        for fid, info in lc.items():
            L += [f"### {fid}: level ({', '.join(info['level'])})", "",
                  f"{len(info['cells'])} cells with plays; {info['atLeastN2016']} have 150 or more in 2016-2023, {info['atLeastN2021']} in 2021-2023.", ""]
            L += _t(["cell", "plays 2016-2023", "plays 2021-2023"], [[f"`{r['key']}`", str(r["n2016"]), str(r["n2021"])] for r in info["cells"]]) + [""]
    cc = d.get("candidateCounts")
    if cc:
        L += ["## 8e. Step 5b candidate late cells (B1, counted before the fit)", "",
              "Unweighted plays per candidate late cell (lateTime: G5, GF, OT; overtime rows included), 2016-2023 and 2021-2023. Cells with fewer than 10 plays are summarised, not listed.", ""]
        for name, info in cc.items():
            big = [r for r in info["cells"] if r["n2016"] >= 10]
            L += [f"### {name}", "", f"{len(info['cells'])} cells; {info['atLeastN2016']} with 150 or more in 2016-2023, {info['atLeastN2021']} in 2021-2023; {len(info['cells']) - len(big)} cells with fewer than 10 plays not listed.", ""]
            L += _t(["cell", "plays 2016-2023", "plays 2021-2023"], [[f"`{r['key']}`", str(r["n2016"]), str(r["n2021"])] for r in big]) + [""]
    l5 = d.get("lateChecks5b")
    if l5:
        L += ["## 8f. Step 5b late checks (B9, in-sample 2016-2023)", "",
              "Thresholds in data/caller/latechecks.json, 5 pp where n >= 100, on 2016-2023 regulation: (a) tied, final 2:00, inside the 37, 3rd down: "
              "field goal and pass rate; (b) trailing 1-8, final 2:00, own half (K75 and K99), 4th down: punt and go rate; (c) leading, final 2:00, downs 1-3, "
              "by can-kneel-out: kneel rate. The same rows in overtime (`.OT`) are shown, not gated.", ""]
        L += _t(["check", "n", "predicted %", "actual %", "status"], [[f"`{r['id']}`", str(r["n"]), _pct(r["predicted"]), _pct(r["actual"]), r["status"]] for r in l5]) + [""]
    lk = d.get("lateChecks")
    if lk:
        L += ["## 8d. Late-game in-sample check (step 5a, B5 and B6)", "",
              "Thresholds in data/caller/latechecks.json: 4th-down field goal rate within 5 pp on 2021-2023 where n >= 100 (`.recent`; `.all` is 2016-2023, shown); "
              "downs 1-3 pass and kneel rate by late score bucket within 5 pp on 2016-2023 where n >= 100. Go and punt rows are shown, not gated.", ""]
        L += _t(["check", "n", "predicted %", "actual %", "status"], [[f"`{r['id']}`", str(r["n"]), _pct(r["predicted"]), _pct(r["actual"]), r["status"]] for r in lk]) + [""]

    # 9
    v: Validation | None = d.get("validation")
    L += ["## 9. Validation", ""]
    if v is None:
        L += ["Not run (`--skip-validation`).", ""]
        return "\n".join(L).rstrip() + "\n"
    L += ["Every in-scope 2024 and 2025 play. Predicted = mean of the caller's predicted probability over the plays in scope. "
          "Actual = share of those plays whose mapped call matches. Tolerance in absolute percentage points, from data/caller/tolerances.json. "
          "Interval = 95% Wilson interval of the actual rate.", ""]
    post_hoc = {g for r in POST_HOC_REVISIONS for g in r["groups"]}
    L += ["**This is not a clean holdout test.** The model was restructured after the first 2024-2025 run, three times:", ""]
    for r in POST_HOC_REVISIONS:
        L += [f"- {r['name']}: {r['what']}"]
    L += ["", "The metrics marked \"yes\" in the \"revised after holdout\" column were shaped with those results in view, so their passes are not "
          "out-of-sample evidence. Only the metrics marked \"no\" still test the caller on data it has not influenced. "
          "Affected metrics: " + ", ".join(m.id for m in v.metrics if m.group in post_hoc) + ".", ""]
    rows = []
    for m in v.metrics:
        ci = wilson(m.hits, m.n)
        diff = None if m.predicted is None else 100 * (m.predicted - (m.actual or 0.0))
        rows.append([m.label, str(m.n), _pct(m.predicted), _pct(m.actual),
                     "-" if diff is None else f"{diff:+.1f}",
                     "-" if ci is None else f"{_pct(ci[0])}-{_pct(ci[1])}", f"{m.tolerance:.1f}",
                     "yes" if m.group in post_hoc else "no", m.status + (f" ({m.note})" if m.note else "")])
    L += _t(["metric", "n", "predicted %", "actual %", "pred - actual", "actual 95%", "tolerance", "revised after holdout", "result"], rows) + [""]
    devs = [x for x in (d.get("tolerances") or {}).get("known_deviations", []) if x.get("approved_by") == "Joseph"]
    L += [f"Approved deviations (data/caller/tolerances.json, approved by Joseph): {len(devs)}.", ""]
    if devs:
        L += _t(["metric", "observed %", "target %", "date", "reason"],
                [[x["metric"], _pct(x.get("observed")), _pct(x.get("target")), str(x.get("date", "")), str(x.get("reason", "")).replace("|", "\\|")] for x in devs]) + [""]
    fails = v.gated_failures
    L += [f"Gated failures: {len(fails)}." + (" " + ", ".join(m.label for m in fails) + "." if fails else ""), ""]
    L += ["4th-down drift: go rate predicted from 2021-2023 vs actual 2024-2025, by zone:", ""]
    L += _t(["zone", "predicted go %", "actual go %", "direction"],
            [[z, _pct(p), _pct(a), "caller under-predicts going for it" if a > p else "caller over-predicts going for it"] for z, (p, a) in v.drift.items()]) + [""]
    lh = d.get("lateHoldout")
    if lh:
        L += ["Late-game rows on 2024-2025 (step 5a, C3), reported and not gated:", ""]
        L += _t(["check", "n", "predicted %", "actual %"], [[f"`{r['id']}`", str(r["n"]), _pct(r["predicted"]), _pct(r["actual"])] for r in lh]) + [""]
    L += ["Odd calls the fitted caller can make (no guard rails in this step):", ""]
    L += _t(["call", "validation situations with a nonzero share", "mean share there %", "max share %"],
            [[k, str(o["situations"]), _pct(o["mean"], 2), _pct(o["max"], 2)] for k, o in v.oddities.items()]) + [""]
    return "\n".join(L).rstrip() + "\n"
